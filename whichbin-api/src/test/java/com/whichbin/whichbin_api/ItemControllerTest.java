package com.whichbin.whichbin_api;

import com.whichbin.whichbin_api.model.Item;
import com.whichbin.whichbin_api.testutil.IntegrationTestHelper;
import org.hamcrest.Matchers;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;
import tools.jackson.databind.ObjectMapper;

import java.util.Set;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
@ActiveProfiles("test")
@AutoConfigureMockMvc
@Transactional
public class ItemControllerTest {
    @Autowired
    private MockMvc mockMvc;
    @Autowired
    private IntegrationTestHelper testHelper;
    @Autowired
    private ObjectMapper objectMapper;

    private Long createItem(
            String token,
            String name,
            boolean recyclable) throws Exception {

        Item item = new Item();
        item.setName(name);
        item.setRecyclable(recyclable);
        item.setLargeItem(false);
        item.setInformation("Test disposal instructions.");
        item.setKeywords(Set.of("test", name.toLowerCase()));

        String response = mockMvc.perform(post("/items")
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(item)))
                .andExpect(status().isCreated())
                .andReturn()
                .getResponse()
                .getContentAsString();

        return objectMapper.readTree(response)
                .get("id")
                .longValue();
    }

    @Test
    void shouldReturnNoItems() throws Exception {
        mockMvc.perform(get("/items"))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                .andExpect(content().json("[]"));
    }

    @Test
    void shouldCreateItemAndRetrieveItById() throws Exception {
        String token = testHelper.getAuthToken();

        String itemJson = """
            {
                "name": "Plastic Bottle",
                "recyclable": true,
                "largeItem": false,
                "information": "Empty and rinse before recycling.",
                "keywords": ["plastic", "bottle", "recycling"]
            }
            """;

        // Create the item
        String response = mockMvc.perform(post("/items")
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("Authorization", "Bearer " + token)
                        .content(itemJson))
                .andExpect(status().isCreated())
                .andExpect(content().contentTypeCompatibleWith(
                        MediaType.APPLICATION_JSON))
                .andExpect(jsonPath("$.id").exists())
                .andReturn()
                .getResponse()
                .getContentAsString();

        // Extract the ID generated by the API
        Long itemId = objectMapper.readTree(response)
                .get("id")
                .asLong();

        // Retrieve the item by its generated ID
        mockMvc.perform(get("/items/{id}", itemId))
                .andExpect(status().isOk())
                .andExpect(content().contentTypeCompatibleWith(
                        MediaType.APPLICATION_JSON))
                .andExpect(jsonPath("$.id").value(itemId))
                 .andExpect(jsonPath("$.name").value("Plastic Bottle"))
                .andExpect(jsonPath("$.recyclable").value(true))
                .andExpect(jsonPath("$.largeItem").value(false))
                .andExpect(jsonPath("$.information")
                        .value("Empty and rinse before recycling."))
                .andExpect(jsonPath("$.keywords",
                        Matchers.containsInAnyOrder("plastic", "bottle", "recycling")))
                .andExpect(jsonPath("$.createdAt").exists())
                .andExpect(jsonPath("$.updatedAt").exists());
    }

    @Test
    void shouldReturnNotFoundForNonexistentItem() throws Exception {
        mockMvc.perform(get("/items/{id}", Long.MAX_VALUE))
                .andExpect(status().isNotFound());
    }

    @Test
    void shouldReturnEmptyListWhenSearchHasNoMatches() throws Exception {
        mockMvc.perform(get("/items")
                        .param("searchText", "nonexistent-item-xyz"))
                .andExpect(status().isOk())
                .andExpect(content().json("[]"));
    }

    @Test
    void shouldSearchItemsByName() throws Exception {
        String token = testHelper.getAuthToken();
        createItem(token, "Plastic Bottle", true);
        createItem(token, "Glass Jar", true);

        mockMvc.perform(get("/items")
                        .param("searchText", "Plastic"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(1))
                .andExpect(jsonPath("$[0].name").value("Plastic Bottle"));
    }

    @Test
    void shouldFilterItemsByRecyclableStatus() throws Exception {
        String token = testHelper.getAuthToken();
        createItem(token, "Plastic Bottle", true);
        createItem(token, "Broken Ceramic", false);

        mockMvc.perform(get("/items")
                        .param("recyclable", "false"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(1))
                .andExpect(jsonPath("$[0].name").value("Broken Ceramic"))
                .andExpect(jsonPath("$[0].recyclable").value(false));
    }

    @Test
    void shouldRejectCreateItemWithoutAuthorization() throws Exception {
        String itemJson = """
            {
                "name": "Plastic Bottle",
                "recyclable": true,
                "largeItem": false,
                "information": "Rinse before recycling.",
                "keywords": ["plastic", "bottle"]
            }
            """;

        mockMvc.perform(post("/items")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(itemJson))
                .andExpect(status().is4xxClientError());
    }

    @Test
    void shouldUpdateExistingItem() throws Exception {
        String token = testHelper.getAuthToken();
        Long itemId = createItem(token, "Plastic Bottle", true);

        String updatedJson = """
            {
                "name": "Plastic Bottle - Updated",
                "recyclable": false,
                "largeItem": true,
                "information": "Updated disposal instructions.",
                "keywords": ["plastic", "updated"]
            }
            """;

        mockMvc.perform(put("/items/{id}", itemId)
                        .header("Authorization", "Bearer " + token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(updatedJson))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(itemId))
                .andExpect(jsonPath("$.name").value("Plastic Bottle - Updated"))
                .andExpect(jsonPath("$.recyclable").value(false))
                .andExpect(jsonPath("$.largeItem").value(true))
                .andExpect(jsonPath("$.information")
                        .value("Updated disposal instructions."));
    }

    @Test
    void shouldDeleteItemAndReturnNotFoundWhenRetrieved() throws Exception {
        String token = testHelper.getAuthToken();
        Long itemId = createItem(token, "Plastic Bottle", true);

        mockMvc.perform(delete("/items/{id}", itemId)
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isNoContent());

        mockMvc.perform(get("/items/{id}", itemId))
                .andExpect(status().isNotFound());
    }
}